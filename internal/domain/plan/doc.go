// Package plan 定义规划领域模型：一次结构化「规划决策」（Decision）中的步骤
// （Step）、动作（Action）、步骤状态（StepStatus），以及决策的校验、解析与
// 依赖调度语义。
//
// 设计原则：
//
//   - **结构化优先**：规划器（或未来的 LLM）输出的是 JSON 决策，而不是自由文本。
//     ParseDecision 负责从模型原始输出里提取 JSON 并规范化，Validate 负责把这些
//     结构约束变成显式错误——「规划输出 100% 通过 schema 校验」的前提是校验逻辑
//     在领域层就存在，而不是散落在调用方；
//   - **纯函数**：本包不读不写任何外部状态（数据库、网络、时钟、日志）。同样的
//     输入永远得到同样的输出，因此可以被穷举测试；
//   - **依赖即调度**：步骤之间用 DependsOn 表达先后关系，ReadySteps 据此计算
//     下一批可执行的步骤；环、自依赖、悬空依赖都在校验期拒绝，避免运行时死锁；
//   - **默认拒绝**：不认识的步骤状态、动作类型、非法 key 一律报错，而不是静默
//     兜底。规划是执行链的上游，脏数据在这里放过，后面只会更难排查。
//
// 术语：
//
//   - 步骤（Step）：任务内唯一的执行单元，key 形如 "recon"、"web-enum"；
//   - 动作（Action）：步骤内的一次具体动作（probe / verify / report / other），
//     通过 StepKey 关联到步骤，可带目标与细节；
//   - 决策（Decision）：一次规划产出的完整结果——可含新步骤、待执行动作、
//     是否已结束（Done）与结束原因（Reason）。
//
// 规模上限（既是防模型跑偏，也是防一次写库过大）：单次决策最多 20 个步骤、
// 10 个动作；步骤 key 长度 1..64。
//
// 本包是纯领域逻辑：只使用标准库，不依赖数据库与其它内部包。
