// Package policy 定义 BeaconX 的执行期策略领域模型：动作裁决（allow / ask /
// deny）、风险等级（Risk）、按优先级匹配的工具调用规则（Rule），以及默认规则集
// （SeedDefaults）与匹配入口 Evaluate。
//
// 设计原则：
//
//   - **纯函数**：Evaluate 只根据「工具名 + 参数 JSON + 规则列表 + 默认动作」
//     计算结果，不读不写数据库、不看时钟、不发事件。同样的输入永远得到同样的
//     输出，因此可以被穷举测试，也可以在事务里先算后写；
//   - **默认询问**：Evaluate 不替调用方决定"没命中时怎么办"，defaultAction 由
//     调用方显式传入；推荐传 Ask（人工审批），把"忘记配置"变成"需要人确认"，
//     而不是静默放行；
//   - **fail closed**：启用规则的正则写错、命中规则的动作非法、默认动作非法，
//     一律返回错误而不是跳过后继续匹配——策略是安全边界，配置错误必须显式；
//   - **优先级即顺序**：priority 越大越先匹配，同优先级保持输入顺序（稳定排序），
//     第一条命中的规则决定结果。规则顺序是策略语义的一部分，不要依赖 map 遍历；
//   - **规则是数据，不是代码**：Rule 可以来自数据库 / API / 内置种子；领域层只
//     负责校验与匹配，持久化、审批流、审计属于上层。
//
// 匹配语义：
//
//   - tool 精确匹配；规则的 tool 为 "*"（或空字符串，容错）时匹配所有工具；
//   - arg_pattern 非空时，对**原始 JSON 文本**做 regexp.MatchString，而不是对
//     解析后的字段做匹配。这样无需理解每个工具的 schema，代价是正则对参数顺序、
//     空白与转义敏感（详见 ArgPattern 的注释）；
//   - Enabled 是配置层的启用开关：Evaluate 只匹配传入的规则、不做 Enabled 过滤，
//     调用方应先只传出生效规则（policy.ActiveRules 或存储层只查 enabled 规则）；
//   - Immutable 是给存储层/UI 的标记：内置底线规则不应被删除或改动作，领域层
//     本身不强制这一点（只做匹配）。
//
// 内置默认规则（SeedDefaults）覆盖五类：GET/HEAD 放行、下载并执行拒绝、删除
// 根目录拒绝、shell 人工审批、HTTP 其他方法人工审批。
//
// 本包是纯领域逻辑：只使用标准库，不依赖数据库与其它内部包。
package policy
